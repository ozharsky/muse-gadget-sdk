#!/usr/bin/env python3
"""Write avatar/bench_videos.h: one registry row per compiled-in clip in avatar/clips/.

A clip header (from video_to_gadget.py v2) defines <NAME>_ENTRY (and the arrays it
names). The registry is derived FROM the clips directory, so removing a clip file is
the whole removal -- regenerate, never hand-edit.

    python3 gen_video_registry.py [clips_dir] [out_header]

Defaults: ~/muse/muse-gadget-sdk/esp32/components/muse/avatar/clips and
bench_videos.h next to it. Entries are sorted by name.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_CLIPS = os.path.expanduser("~/muse/muse-gadget-sdk/esp32/components/muse/avatar/clips")
DEFAULT_OUT = os.path.join(os.path.dirname(DEFAULT_CLIPS), "bench_videos.h")


def scan(clips_dir):
    """[(name, header_file)] for every clip header that defines <NAME>_ENTRY."""
    out = []
    for fn in sorted(os.listdir(clips_dir)):
        if not fn.endswith(".h"):
            continue
        path = os.path.join(clips_dir, fn)
        with open(path, encoding="utf-8", errors="replace") as f:
            text = f.read()
        m = re.search(r"^#define\s+([A-Z0-9_]+)_ENTRY\b", text, re.M)
        if not m:
            print(f"warning: {fn} defines no <NAME>_ENTRY, skipped", file=sys.stderr)
            continue
        out.append((m.group(1).lower(), fn))
    return sorted(out)


def main():
    clips_dir = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_CLIPS
    out_path = sys.argv[2] if len(sys.argv) > 2 else DEFAULT_OUT
    clips = scan(clips_dir)

    lines = [
        "// Generated by gen_video_registry.py from avatar/clips/. Do not edit.",
        "// One row per compiled-in video_to_gadget.py v2 clip (--format u8|i4).",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
    ]
    for _, fn in clips:
        lines.append(f'#include "clips/{fn}"')
    lines += [
        "",
        "static const struct bench_video_t {",
        "    const char *name;",
        "    uint16_t count;",
        "    uint16_t fps;",
        "    uint8_t npal;",
        "    uint8_t fmt;",
        "    const uint16_t *pal;",
        "    const uint8_t *frames;",
        "} BENCH_VIDEOS[] = {",
    ]
    for name, _ in clips:
        lines.append(f"    {name.upper()}_ENTRY,")
    lines += [
        "};",
        "#define BENCH_VIDEO_COUNT ((int)(sizeof(BENCH_VIDEOS) / sizeof(BENCH_VIDEOS[0])))",
        "",
    ]
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"{out_path}: {len(clips)} clip(s): {', '.join(n for n, _ in clips) or '(none)'}")


if __name__ == "__main__":
    main()
