"""Write sprite_stone.h (B3): the B3 obsidian avatar's sprite, palette, kinds, geometry and the 21 pose tables.

Stage B copy of hermes-anim/make_stone_header.py, re-pointed at the B3 pack (poses_b3/, base_b3_384.png)
and the B3 eye templates (4 template rows at EYE_ROW0=26, cols (17, 37)).
"""
import sys

import numpy as np

import hermes_char as fw
import avatar_render as sr
from build import EYES_ONLY

POSES = ["alert", "angry", "bored", "closed", "confused_l", "confused_r", "disgust", "evil", "laugh", "mouth_1", "mouth_2", "nervous_l", "nervous_r",
         "pleased", "proud", "sleepy", "smirk", "squint", "surprised", "target", "wink"]


def arr(vals, per=24):
    v = [str(int(x)) for x in vals]
    return ",\n    ".join(", ".join(v[i:i + per]) for i in range(0, len(v), per))


P = sr.Poses("poses_b3", "base_b3_384.png", EYES_ONLY)
zone_pos = np.nonzero(fw.EYE_ZONES.ravel())[0]
out = ["// Generated by faces_v2/stage_b/stone/pack/make_stone_header.py - the B3 obsidian oracle (stage B art). Do not edit by hand.",
       "#pragma once", "#include <stdint.h>", "",
       f"#define SPR_N {fw.SPR_N}"]
for k, v in fw.IDX.items():
    out.append(f"#define {k} {v}")
for n in ("STONE_M", "STONE_L", "SKIN", "HI2", "HI"):
    out.append(f"#define IDX_{n} {fw.NAME[n]}")
out += ["", "static const uint8_t SPR_PAL[SPR_N][3] = {", "    " + ",\n    ".join("{ %d, %d, %d }" % tuple(c) for c in fw.PAL), "};",
        f"static const uint8_t SPR_BRIGHT[SPR_N] = {{ {', '.join(str(int(x)) for x in fw.BRIGHT)} }};",
        f"/* 1 = the glow family (the lens fill): takes the state's colour. The gold rims, cracks and stone keep their own. */",
        f"static const uint8_t SPR_GLOW[SPR_N] = {{ {', '.join(str(int(x)) for x in fw.GLOW_FAMILY)} }};",
        "/* Base sprite (palette indices). The eye pixels (kind 2) are wiped each frame; the eyes are drawn procedurally or by a pose. */",
        "static const uint8_t SPR[64 * 64] = {", "    " + arr(fw.SPR.ravel(), 64), "};",
        "/* 0 none, 1 glints along the gold cracks, 2 eye lens, 3 shimmer in the shadow planes */",
        "static const uint8_t SPR_KIND[64 * 64] = {", "    " + arr(fw.KIND.ravel(), 64), "};", "",
        "/* Geometry of the effects for this face (it fills the frame). */",
        f"#define EYE_ROW0 {fw.EYE_ROW0}", f"#define EYE_COL0_L {fw.EYE_COL0[0]}", f"#define EYE_COL0_R {fw.EYE_COL0[1]}",
        "static const int8_t EYE_T[4][2] = { { 1, 6 }, { 0, 7 }, { 0, 8 }, { 1, 7 } };                                  /* glow x range per template row 0..3 */",
        "static const int8_t EYE_WIDE[6][2] = { { 2, 5 }, { 1, 6 }, { 0, 7 }, { 0, 8 }, { 1, 7 }, { 2, 6 } };            /* wide eyes: rows -1..4 */",
        "#define EYES_R0 %d\n#define EYES_R1 %d\n#define EYES_C0 %d\n#define EYES_C1 %d" % (*fw.EYES_BOX[:2], *fw.EYES_BOX[2:]),
        f"#define EYE_ZONE_N {len(zone_pos)}",
        "static const uint16_t EYE_ZONE_POS[EYE_ZONE_N] = {", "    " + arr(zone_pos, 24), "};", ""]
out.append("enum {\n    " + ",\n    ".join(("POSE_" + n.upper()) for n in POSES) + ",\n    POSE_COUNT\n};")
tab = []
for n in POSES:
    idx, mask, zone = P.get(n)
    rest = mask & ~zone
    pos = np.nonzero(rest.ravel())[0]
    val = idx.ravel()[pos]
    u = n.upper()
    out.append(f"static const uint16_t P_{u}_POS[] = {{\n    {arr(pos, 24)}\n}};")
    out.append(f"static const uint8_t P_{u}_VAL[] = {{\n    {arr(val, 48)}\n}};")
    if zone.any():
        zv = idx[zone]                                    # row-major over the eye zones, same order as EYE_ZONE_POS
        out.append(f"static const uint8_t P_{u}_ZONE[EYE_ZONE_N] = {{\n    {arr(zv, 30)}\n}};")
        tab.append(f"    [POSE_{u}] = {{ P_{u}_POS, P_{u}_VAL, {len(pos)}, P_{u}_ZONE }},")
    else:
        tab.append(f"    [POSE_{u}] = {{ P_{u}_POS, P_{u}_VAL, {len(pos)}, 0 }},")
out.append("typedef struct { const uint16_t *pos; const uint8_t *val; uint16_t n; const uint8_t *zone; } pose_t;")
out.append("static const pose_t POSE_TABLE[POSE_COUNT] = {\n" + "\n".join(tab) + "\n};")
open(sys.argv[1], "w").write("\n".join(out) + "\n")
print("wrote", sys.argv[1], sum(len(l) for l in out) // 1024, "KB source;", len(POSES), "poses")
