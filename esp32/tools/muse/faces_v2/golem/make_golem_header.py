"""Write sprite_golem.h (C5 terracotta automaton): palette, kinds, the six IDX roles.

Geometry baked in (kept in comments for the C side, stage D wires them):
  eye centres (21.5,29) / (41.5,29), ring rx 6.3 ry 6.5, lens 38 px each (cap 48)
  mouth slot x28..35, rows 37..40; chest core seal (31.5,51.5)
"""
import sys

import golem_char as gc


def arr(vals, per=64):
    v = [str(int(x)) for x in vals]
    return ",\n    ".join(", ".join(v[i:i + per]) for i in range(0, len(v), per))


IDX = dict(SOCKET=gc.IDX["DEEP"], LID=gc.IDX["DEEP"], DARK=gc.IDX["DEEP"],
           SKIN=gc.IDX["PLATE"], BLACK=gc.IDX["BLACK"])
BRIGHT = [0, 4, 9, 2, 5, 6, 7, 8, 9, 9]   # BLACK self; DEEP->RUST; PLATE->GLINT; TAN->PLATE; RUST->TERRA_D; D->M; M->L; L->IRIS; IRIS->GLINT; GLINT self

out = [
    "// Generated by faces_v2/stage_b/golem/pack/make_golem_header.py - the C5 terracotta automaton (stage B art). Do not edit by hand.",
    "// Geometry: eye centres (21.5,29)/(41.5,29) ring rx 6.3 ry 6.5; lens = kind 2, 38 px per eye (needs the eye_t cap 48).",
    "// Mouth slot x28..35 rows 37..40; the carved smile at rows 37..38 IS the closed mouth. Core seal centred (31.5,51.5).",
    "#pragma once",
    "#include <stdint.h>",
    "",
    "#define SPR_N %d" % gc.SPR_N,
]
for k, v in IDX.items():
    out.append("#define IDX_%s %d" % (k, v))
out.append("#define IDX_EYE_R %d" % gc.IDX["IRIS"])
out.append("#define IDX_EYE_U %d" % gc.IDX["GLINT"])
out += [
    "",
    "static const uint8_t SPR_PAL[SPR_N][3] = {",
    "    " + ",\n    ".join("{ %d, %d, %d }" % tuple(c) for c in gc.PAL),
    "};",
    "static const uint8_t SPR_BRIGHT[SPR_N] = { %s };   /* one ramp step up per family (the clay shimmer walks this) */" % ", ".join(str(b) for b in BRIGHT),
    "static const uint8_t SPR[64 * 64] = {",
    "    " + arr(gc.SPR.ravel()),
    "};",
    "/* 0 none, 1 clay glints (shell specks), 2 eye lens, 3 clay shimmer (dark shell mottle) */",
    "static const uint8_t SPR_KIND[64 * 64] = {",
    "    " + arr(gc.KIND.ravel()),
    "};",
]
text = "\n".join(out) + "\n"
open(sys.argv[1], "w", newline="\n").write(text)
print("wrote", sys.argv[1], len(text) // 1024, "KB;", gc.SPR_N, "colours;",
      int((gc.KIND == 2).sum()), "lens px;", int((gc.KIND == 1).sum()), "glints;", int((gc.KIND == 3).sum()), "shimmer")
